"""Run the leakage audit on the cached KOI catalogue and write a Markdown report.

Exits non-zero if any catalogue column is unclassified, or (with --strict) if an allowed
feature exceeds the univariate audit thresholds.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

import pandas as pd

from exoplanet.config import load_config
from exoplanet.data.catalogue import load_koi_catalogue
from exoplanet.data.labels import LABEL, PARAMETER_PROVENANCE, label_catalogue
from exoplanet.features.leakage import DENY_CATEGORIES, flag_suspicious, univariate_audit
from exoplanet.features.tabular import FEATURE_GROUPS, classify_column, unclassified_columns
from exoplanet.reporting import markdown_table


def _sample_row(df: pd.DataFrame) -> dict[str, float]:
    return {
        "kois": len(df),
        "stars": df["kepid"].nunique(),
        "positive_fraction": df[LABEL].mean(),
    }


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--config", default=None, help="path to a YAML config")
    parser.add_argument(
        "--output", default=None, help="report path (default: outputs/leakage_audit_results.md)"
    )
    parser.add_argument("--strict", action="store_true", help="fail on flagged allowed features")
    args = parser.parse_args()

    config = load_config(args.config)
    df = load_koi_catalogue(config)

    unclassified = unclassified_columns(df.columns)
    if unclassified:
        sys.exit(
            f"Unclassified catalogue columns (add to a feature group or deny list): {unclassified}"
        )

    all_labelled = label_catalogue(df, {**config, "sample": {}})
    sample = label_catalogue(df, config)

    classification = pd.Series({c: classify_column(c) for c in df.columns}, name="class")
    numeric = [c for c in sample.select_dtypes("number").columns if c != LABEL]
    audit = univariate_audit(sample[numeric], sample[LABEL])
    audit.insert(0, "class", classification.reindex(audit.index))

    allowed = audit[audit["class"].str.startswith("allowed")]
    lk = config["leakage"]
    flags = flag_suspicious(allowed, lk["max_value_auc"], lk["max_missing_auc"])
    denied_top = audit[audit["class"].str.startswith("denied")].head(15)

    provenance = pd.crosstab(all_labelled[PARAMETER_PROVENANCE], all_labelled[LABEL])
    provenance["positive_fraction"] = provenance[1] / provenance.sum(axis=1)

    policy = classification.value_counts().rename_axis("class").to_frame("n_columns").sort_index()
    policy["reason"] = [
        DENY_CATEGORIES[c.split(":", 1)[1]] if c.startswith("denied") else "" for c in policy.index
    ]

    samples = pd.DataFrame(
        {"all labelled": _sample_row(all_labelled), "modelling sample": _sample_row(sample)}
    ).T.rename_axis("sample")
    samples[["kois", "stars"]] = samples[["kois", "stars"]].astype(int)

    report = [
        "# Leakage Audit Results",
        "",
        "Generated by `scripts/audit_leakage.py`. Policy and rationale: "
        "[leakage_audit.md](leakage_audit.md).",
        "",
        "## Modelling sample",
        "",
        f"Parameter provenance filter: `{config['sample'].get('parameter_provenance')}`",
        "",
        markdown_table(samples),
        "",
        "Labelled KOIs by parameter provenance (label 1 = CONFIRMED):",
        "",
        markdown_table(provenance),
        "",
        "## Column policy",
        "",
        f"All {len(classification)} catalogue columns are classified; none are unclassified.",
        "",
        markdown_table(policy),
        "",
        "Allowed groups: "
        + "; ".join(f"`{g}` ({len(c)})" for g, c in FEATURE_GROUPS.items())
        + f". Enabled by config: `{config['features']['groups']}`.",
        "",
        "## Univariate audit of allowed features",
        "",
        "Symmetrised AUC of each feature alone (median-imputed) and of its missingness "
        f"indicator, on the modelling sample. Thresholds: value > {lk['max_value_auc']}, "
        f"missingness > {lk['max_missing_auc']}.",
        "",
        f"**Flagged: {len(flags)}**"
        + (" (" + ", ".join(f"`{c}`" for c in flags.index) + ")" if len(flags) else ""),
        "",
        markdown_table(allowed, floatfmt=".3f"),
        "",
        "## Strongest denied columns",
        "",
        "For reference: denied numeric columns with the highest univariate AUC.",
        "",
        markdown_table(denied_top, floatfmt=".3f"),
        "",
    ]

    output = (
        Path(args.output)
        if args.output
        else config["paths"]["outputs_dir"] / "leakage_audit_results.md"
    )
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text("\n".join(report), encoding="utf-8")
    print(f"Report: {output}")
    print(f"Modelling sample: {len(sample)} KOIs; flagged allowed features: {list(flags.index)}")
    if args.strict and len(flags):
        sys.exit(1)


if __name__ == "__main__":
    main()
