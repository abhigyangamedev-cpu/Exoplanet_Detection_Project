"""Cross-validate and train the two-tower light-curve CNN on the shared development folds.

Writes out-of-fold scores (same format as the tabular baseline), a cross-validation report
with per-epoch validation learning curves, and a final model trained on all development KOIs
with views. The held-out test set is not scored here.
"""

from __future__ import annotations

import argparse
import json
from datetime import UTC, datetime
from pathlib import Path

import torch

from exoplanet.config import load_config, set_seed
from exoplanet.data.catalogue import load_koi_catalogue
from exoplanet.data.labels import label_catalogue
from exoplanet.data.lightcurves import load_views
from exoplanet.data.splits import KOI, SPLIT, TEST, load_splits, splits_path
from exoplanet.evaluation.metrics import pooled_pr_auc, summarise_folds
from exoplanet.features.leakage import assert_no_leakage
from exoplanet.models.cnn import attach_scalars, cross_validate, fit_final
from exoplanet.reporting import markdown_table


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--config", default=None, help="path to a YAML config")
    parser.add_argument("--name", default="cnn", help="model name for artefacts (default: cnn)")
    parser.add_argument(
        "--local-views",
        nargs="+",
        default=None,
        help="views stacked as local-tower channels (default: cnn.local_views)",
    )
    parser.add_argument(
        "--scalars",
        nargs="*",
        default=None,
        help="catalogue columns fed to the head as log10 scalars (default: cnn.scalars)",
    )
    parser.add_argument(
        "--output", default=None, help="report path (default: outputs/<name>_cv.md)"
    )
    parser.add_argument(
        "--no-final", action="store_true", help="skip refitting on all dev KOIs (CV only)"
    )
    parser.add_argument(
        "--device",
        default="auto",
        help="torch device for training, e.g. cpu or cuda (default: auto, cuda if available)",
    )
    args = parser.parse_args()

    config = load_config(args.config)
    seed = config["seed"]
    set_seed(seed)
    params = dict(config["cnn"])
    if args.scalars is not None:
        params["scalars"] = args.scalars
    if args.local_views is not None:
        params["local_views"] = args.local_views
    device = args.device
    if device == "auto":
        device = "cuda" if torch.cuda.is_available() else "cpu"
    params["device"] = device
    print(f"Training on {device}")
    scalars = params.get("scalars") or []
    assert_no_leakage(scalars)

    splits = load_splits(config)
    views = load_views(config, splits[KOI])
    if scalars:
        sample = label_catalogue(load_koi_catalogue(config), config).set_index(KOI)
        views = attach_scalars(views, sample, scalars)
    dev = splits[splits[SPLIT] != TEST]
    coverage = dev[KOI].isin(views.index).mean()
    print(f"Views for {len(views)}/{len(splits)} KOIs ({coverage:.1%} of development KOIs)")

    oof, fold_metrics, curves = cross_validate(views, splits, params, seed)

    outputs, models = config["paths"]["outputs_dir"], config["paths"]["models_dir"]
    outputs.mkdir(parents=True, exist_ok=True)
    oof_path = outputs / f"{args.name}_oof.csv"
    oof.to_csv(oof_path)

    if not args.no_final:
        splits_meta = json.loads(
            splits_path(config).with_suffix(".meta.json").read_text(encoding="utf-8")
        )
        model = fit_final(views, splits, params, seed)
        models.mkdir(parents=True, exist_ok=True)
        model_path = models / f"{args.name}.pt"
        torch.save(
            {
                "state_dict": model.state_dict(),
                "params": params,
                "views": config["views"],
                "lightcurves": config["lightcurves"],
                "provenance": {
                    "created_utc": datetime.now(UTC).isoformat(timespec="seconds"),
                    "catalogue_sha256": splits_meta["catalogue_sha256"],
                    "splits_created_utc": splits_meta["created_utc"],
                    "seed": seed,
                    "n_train": int(len(oof)),
                    "torch_version": str(torch.__version__),
                },
            },
            model_path,
        )
        print(f"Model: {model_path}")

    summary = summarise_folds(fold_metrics)
    pooled = pooled_pr_auc(oof)
    every = max(1, len(curves) // 10)
    shown = curves.iloc[[*range(every - 1, len(curves), every)]]
    if shown.index[-1] != curves.index[-1]:
        shown = curves.iloc[[*range(every - 1, len(curves), every), -1]]
    shown = shown.assign(mean=shown.mean(axis=1))
    shown.columns = [f"fold {c}" if isinstance(c, int) else c for c in shown.columns]
    report = [
        "# Light-Curve CNN: Cross-Validation",
        "",
        "Generated by `scripts/train_cnn.py`. Two-tower 1D CNN on global and local views, "
        f"evaluated on the {len(summary) - 2} host-star grouped development folds. The held-out "
        "test set is not used.",
        "",
        f"- Development KOIs with views: {coverage:.1%} (KOIs without views are excluded, not "
        "imputed; compare models on the same KOIs)",
        f"- Pooled out-of-fold PR-AUC: **{pooled:.3f}** (a random classifier scores the "
        f"positive fraction, {oof['label'].mean():.3f})",
        f"- {params['epochs']} epochs (fixed; no early stopping), batch {params['batch_size']}, "
        f"AdamW lr {params['learning_rate']}, weight decay {params['weight_decay']}, "
        f"flip augmentation {params['flip_augment']}; seed {seed}; torch {torch.__version__}; "
        f"device {device}",
        f"- Architecture: `{params['arch']}`",
        "",
        "## Per-fold metrics",
        "",
        markdown_table(summary, floatfmt=".3f"),
        "",
        "## Validation PR-AUC by epoch",
        "",
        "Monitoring only: the validation folds never stop training or select a checkpoint.",
        "",
        markdown_table(shown, floatfmt=".3f"),
        "",
    ]
    output = Path(args.output) if args.output else outputs / f"{args.name}_cv.md"
    output.write_text("\n".join(report), encoding="utf-8")

    print(f"OOF scores: {oof_path}\nReport: {output}")
    print(summary.to_string(float_format="%.3f"))
    print(f"Pooled OOF PR-AUC: {pooled:.3f}")


if __name__ == "__main__":
    main()
