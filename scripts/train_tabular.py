"""Cross-validate and train the tabular baseline on the shared development folds.

Writes out-of-fold scores (for the later precision-recall comparison with the CNN), a
cross-validation report, and a final model refit on all development KOIs. The held-out test
set is not scored here.
"""

from __future__ import annotations

import argparse
import json
from datetime import UTC, datetime
from pathlib import Path

import joblib
import sklearn

from exoplanet.config import load_config, set_seed
from exoplanet.data.catalogue import load_koi_catalogue
from exoplanet.data.labels import label_catalogue
from exoplanet.data.splits import KOI, load_splits, splits_path
from exoplanet.features.tabular import select_features
from exoplanet.models.tabular import cross_validate, fit_final, pooled_pr_auc, summarise_folds
from exoplanet.reporting import markdown_table


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--config", default=None, help="path to a YAML config")
    parser.add_argument(
        "--output", default=None, help="report path (default: outputs/tabular_cv.md)"
    )
    args = parser.parse_args()

    config = load_config(args.config)
    seed = config["seed"]
    set_seed(seed)
    tc, groups = config["tabular"], config["features"]["groups"]

    sample = label_catalogue(load_koi_catalogue(config), config).set_index(KOI)
    features = select_features(sample, groups)
    splits = load_splits(config)

    oof, fold_metrics, importance = cross_validate(
        features, splits, tc["params"], seed, tc["permutation_repeats"]
    )
    model = fit_final(features, splits, tc["params"], seed)

    outputs, models = config["paths"]["outputs_dir"], config["paths"]["models_dir"]
    outputs.mkdir(parents=True, exist_ok=True)
    models.mkdir(parents=True, exist_ok=True)
    oof_path = outputs / "tabular_oof.csv"
    oof.to_csv(oof_path)

    splits_meta = json.loads(
        splits_path(config).with_suffix(".meta.json").read_text(encoding="utf-8")
    )
    provenance = {
        "created_utc": datetime.now(UTC).isoformat(timespec="seconds"),
        "catalogue_sha256": splits_meta["catalogue_sha256"],
        "splits_created_utc": splits_meta["created_utc"],
        "seed": seed,
        "feature_groups": groups,
        "features": list(features.columns),
        "params": tc["params"],
        "n_train": int(len(oof)),
        "sklearn_version": sklearn.__version__,
    }
    model_path = models / tc["model_filename"]
    joblib.dump({"model": model, "provenance": provenance}, model_path)

    summary = summarise_folds(fold_metrics)
    pooled = pooled_pr_auc(oof)
    report = [
        "# Tabular Baseline: Cross-Validation",
        "",
        "Generated by `scripts/train_tabular.py`. Histogram gradient boosting on catalogue "
        f"feature groups `{groups}` ({features.shape[1]} features), evaluated on the "
        f"{len(summary) - 2} host-star grouped development folds. The held-out test set is "
        "not used.",
        "",
        f"- Pooled out-of-fold PR-AUC: **{pooled:.3f}** (a random classifier scores the "
        f"positive fraction, {oof['label'].mean():.3f})",
        f"- Parameters: `{tc['params']}`; seed {seed}; scikit-learn {sklearn.__version__}",
        "",
        "## Per-fold metrics",
        "",
        markdown_table(summary, floatfmt=".3f"),
        "",
        "## Permutation importance",
        "",
        f"Mean drop in validation PR-AUC when a feature is shuffled "
        f"({tc['permutation_repeats']} repeats per fold, averaged over folds). A single "
        "dominant feature would warrant a leakage check.",
        "",
        markdown_table(importance, floatfmt=".4f"),
        "",
    ]
    output = Path(args.output) if args.output else outputs / "tabular_cv.md"
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text("\n".join(report), encoding="utf-8")

    print(f"Model: {model_path}\nOOF scores: {oof_path}\nReport: {output}")
    print(summary.to_string(float_format="%.3f"))
    print(f"Pooled OOF PR-AUC: {pooled:.3f}")


if __name__ == "__main__":
    main()
