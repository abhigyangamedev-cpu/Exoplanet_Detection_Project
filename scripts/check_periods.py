"""Check that folding on the catalogue period produces a coherent transit in every view.

A mis-stated period smears the transits across phase, so the local view carries no dip at
mid-transit. For every KOI with views this computes ``view_transit_snr`` (central dip depth
over out-of-transit scatter) and flags views below a threshold. Flagged KOIs are reported,
not removed: the CNN still scores them, and the report shows how it scores them.
"""

from __future__ import annotations

import argparse
from pathlib import Path

import numpy as np
import pandas as pd

from exoplanet.config import load_config
from exoplanet.data.catalogue import load_koi_catalogue
from exoplanet.data.labels import LABEL, label_catalogue
from exoplanet.data.lightcurves import load_views
from exoplanet.data.splits import KOI, SPLIT, load_splits
from exoplanet.features.lightcurve import view_transit_snr
from exoplanet.reporting import markdown_table


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--config", default=None, help="path to a YAML config")
    parser.add_argument("--threshold", type=float, default=3.0, help="flag views below this")
    parser.add_argument("--cnn", default="cnn_full", help="model whose dev OOF scores to show")
    parser.add_argument(
        "--output", default=None, help="report path (default: outputs/period_check.md)"
    )
    args = parser.parse_args()
    config = load_config(args.config)
    local_durations = config["views"]["local_durations"]

    splits = load_splits(config).set_index(KOI)
    views = load_views(config, splits.index)
    sample = label_catalogue(load_koi_catalogue(config), config).set_index(KOI)
    snr = views["local_view"].map(lambda v: view_transit_snr(np.asarray(v), local_durations))
    table = pd.DataFrame(
        {
            "view_snr": snr,
            LABEL: splits.loc[views.index, LABEL],
            "partition": np.where(splits.loc[views.index, SPLIT] == "test", "test", "dev"),
            "koi_period": sample.loc[views.index, "koi_period"],
            "koi_model_snr": sample.loc[views.index, "koi_model_snr"],
            "n_in_transit": views["n_in_transit"],
        }
    )
    oof_path = config["paths"]["outputs_dir"] / f"{args.cnn}_oof.csv"
    if oof_path.exists():
        table[args.cnn] = pd.read_csv(oof_path, index_col=KOI)["score"]
    flagged = table[table["view_snr"] < args.threshold].sort_values("view_snr")

    summary = (
        table.assign(flagged=table["view_snr"] < args.threshold)
        .groupby(["partition", LABEL])
        .agg(
            kois=("view_snr", "size"),
            flagged=("flagged", "sum"),
            median_view_snr=("view_snr", "median"),
        )
    )
    summary["flagged_fraction"] = summary["flagged"] / summary["kois"]
    corr = table[["view_snr", "koi_model_snr"]].corr(method="spearman").iloc[0, 1]

    report = [
        "# Period Check: Is the Transit Coherent at the Catalogue Period?",
        "",
        "Generated by `scripts/check_periods.py`. For each of the "
        f"{len(table)} KOIs with views, `view_snr` = depth of the local view's centre "
        "(within a quarter duration of mid-transit) over the robust scatter of its "
        "out-of-transit bins. Folding on a wrong period smears the transits across phase and "
        f"drives this toward 0 (see `tests/test_lightcurve.py`). Threshold: {args.threshold}.",
        "",
        f"- Flagged: **{len(flagged)} of {len(table)}** views ({len(flagged) / len(table):.1%}).",
        f"- `view_snr` tracks the catalogue's transit SNR (Spearman {corr:.2f}), so most flags "
        "are faint signals rather than wrong periods; a wrong period would leave a "
        "high-`koi_model_snr` KOI with a flat view.",
        "",
        markdown_table(summary, floatfmt=".3g"),
        "",
        "## Flagged views with high catalogue SNR (possible period problems)",
        "",
        "Flagged KOIs whose catalogue SNR is above 20, where a clear dip was expected.",
        "",
        markdown_table(flagged[flagged["koi_model_snr"] > 20].head(25), floatfmt=".3g"),
        "",
        "## Weakest views",
        "",
        markdown_table(flagged.head(15), floatfmt=".3g"),
        "",
    ]
    output = (
        Path(args.output) if args.output else config["paths"]["outputs_dir"] / "period_check.md"
    )
    output.write_text("\n".join(report), encoding="utf-8")
    print(summary.to_string(float_format="%.3g"))
    print(
        f"flagged {len(flagged)}; with koi_model_snr > 20: "
        f"{(flagged['koi_model_snr'] > 20).sum()}; spearman {corr:.2f}"
    )
    print(f"Report: {output}")


if __name__ == "__main__":
    main()
