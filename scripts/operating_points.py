"""Operating points in follow-up terms: what each threshold costs in telescope time.

For each model, thresholds are chosen on development out-of-fold scores for a target
precision or a target recall, then expressed as confirmed planets found, false positives
sent to follow-up, and follow-up targets per planet found. The same dev-chosen thresholds
are applied to the saved test-set scores (``outputs/evaluation_test_scores.csv``): nothing
is retrained or re-scored, and no choice is made on test data.
"""

from __future__ import annotations

import argparse
from pathlib import Path

import numpy as np
import pandas as pd

from exoplanet.config import load_config
from exoplanet.data.labels import LABEL
from exoplanet.data.splits import KOI
from exoplanet.evaluation.metrics import SCORE
from exoplanet.evaluation.pr import operating_point
from exoplanet.reporting import markdown_table

TARGETS = [
    ("precision", 0.99),
    ("precision", 0.95),
    ("precision", 0.90),
    ("recall", 0.90),
    ("recall", 0.95),
]


def threshold_for(label: np.ndarray, score: np.ndarray, metric: str, target: float) -> float:
    """Dev threshold: lowest score with precision >= target (maximising recall), or highest
    score with recall >= target (maximising precision)."""
    order = np.argsort(-score, kind="stable")
    s, y = score[order], label[order]
    tp = np.cumsum(y)
    precision = tp / np.arange(1, len(y) + 1)
    recall = tp / y.sum()
    last = np.r_[s[1:] != s[:-1], True]  # only cut between distinct scores
    ok = np.flatnonzero(
        last & ((precision >= target) if metric == "precision" else (recall >= target))
    )
    if not len(ok):
        raise ValueError(f"{metric} never reaches {target}")
    return float(s[ok[-1]] if metric == "precision" else s[ok[0]])


def describe(label: np.ndarray, score: np.ndarray, threshold: float) -> dict[str, float]:
    op = operating_point(label, score, threshold)
    sent = op["tp"] + op["fp"]
    return {
        "threshold": threshold,
        "precision": op["precision"],
        "recall": op["recall"],
        "planets_found": op["tp"],
        "planets_missed": op["fn"],
        "wasted_followups": op["fp"],
        "followups_per_planet": sent / op["tp"] if op["tp"] else float("nan"),
    }


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--config", default=None, help="path to a YAML config")
    parser.add_argument("--models", nargs="+", default=["tabular", "tabular_lc", "cnn_full"])
    parser.add_argument(
        "--output", default=None, help="report path (default: outputs/operating_points.md)"
    )
    args = parser.parse_args()
    config = load_config(args.config)
    outputs = config["paths"]["outputs_dir"]

    oof = {m: pd.read_csv(outputs / f"{m}_oof.csv", index_col=KOI) for m in args.models}
    common = sorted(set.intersection(*(set(o.index) for o in oof.values())))
    labels = oof[args.models[0]].loc[common, LABEL].to_numpy()
    test_path = outputs / "evaluation_test_scores.csv"
    test = pd.read_csv(test_path) if test_path.exists() else None

    dev_rows, test_rows = [], []
    for model in args.models:
        score = oof[model].loc[common, SCORE].to_numpy()
        for metric, target in TARGETS:
            thr = threshold_for(labels, score, metric, target)
            key = {"model": model, "target": f"{metric} {target:.2f}"}
            dev_rows.append(key | describe(labels, score, thr))
            if test is not None and model in test.columns:
                test_rows.append(
                    key | describe(test[LABEL].to_numpy(), test[model].to_numpy(), thr)
                )
    dev_table = pd.DataFrame(dev_rows).set_index(["model", "target"])
    report = [
        "# Operating Points in Follow-up Terms",
        "",
        "Generated by `scripts/operating_points.py`. Thresholds are chosen on development "
        f"out-of-fold scores ({len(common)} KOIs scored by every model listed). "
        "`wasted_followups`: false positives that would be sent to follow-up observation; "
        "`followups_per_planet`: targets observed per confirmed planet found (1.00 is perfect).",
        "",
        "## Development folds",
        "",
        markdown_table(dev_table.reset_index(), floatfmt=".3f"),
        "",
    ]
    if test_rows:
        test_table = pd.DataFrame(test_rows).set_index(["model", "target"])
        report += [
            "## Held-out test set (dev-chosen thresholds applied unchanged)",
            "",
            "From the saved test scores of the models scored once on the test set; no model "
            "was retrained or re-scored.",
            "",
            markdown_table(test_table.reset_index(), floatfmt=".3f"),
            "",
        ]
    output = Path(args.output) if args.output else outputs / "operating_points.md"
    output.write_text("\n".join(report), encoding="utf-8")
    print(dev_table.to_string(float_format="%.3f"))
    if test_rows:
        print(test_table.to_string(float_format="%.3f"))
    print(f"Report: {output}")


if __name__ == "__main__":
    main()
