"""Create host-star grouped train/validation/test splits for the modelling sample.

Splits are created once and reused by every model. Existing splits are not overwritten
without --force, since regenerating them after evaluation would invalidate comparisons.
"""

from __future__ import annotations

import argparse
import json
import sys
from datetime import UTC, datetime
from pathlib import Path

import sklearn

from exoplanet.config import load_config
from exoplanet.data.catalogue import catalogue_path, load_koi_catalogue, metadata_path
from exoplanet.data.labels import label_catalogue
from exoplanet.data.splits import make_splits, save_splits, splits_path, summarise_splits
from exoplanet.reporting import markdown_table


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--config", default=None, help="path to a YAML config")
    parser.add_argument("--force", action="store_true", help="overwrite existing splits")
    parser.add_argument(
        "--output", default=None, help="summary path (default: outputs/splits_summary.md)"
    )
    args = parser.parse_args()

    config = load_config(args.config)
    if splits_path(config).exists() and not args.force:
        sys.exit(f"{splits_path(config)} exists; pass --force to regenerate it")

    sample = label_catalogue(load_koi_catalogue(config), config)
    sc = config["splits"]
    splits = make_splits(
        sample, sc["test_fraction"], sc["n_folds"], config["seed"], sc["group_column"]
    )

    catalogue_meta = json.loads(metadata_path(catalogue_path(config)).read_text(encoding="utf-8"))
    provenance = {
        "created_utc": datetime.now(UTC).isoformat(timespec="seconds"),
        "catalogue_sha256": catalogue_meta["sha256"],
        "seed": config["seed"],
        "splits": sc,
        "sample": config["sample"],
        "n_kois": len(splits),
        "sklearn_version": sklearn.__version__,
    }
    path = save_splits(splits, config, provenance)

    summary = summarise_splits(splits, sc["group_column"])
    report = [
        "# Data Splits",
        "",
        "Generated by `scripts/make_splits.py`. Grouped by `kepid` (no host star appears in "
        "more than one partition) and stratified by label.",
        "",
        f"- Catalogue SHA-256: `{provenance['catalogue_sha256']}`",
        f"- Seed: {provenance['seed']}; test fraction: {sc['test_fraction']}; "
        f"dev folds: {sc['n_folds']}; scikit-learn {provenance['sklearn_version']}",
        "",
        markdown_table(summary, floatfmt=".3f"),
        "",
    ]
    output = (
        Path(args.output) if args.output else config["paths"]["outputs_dir"] / "splits_summary.md"
    )
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text("\n".join(report), encoding="utf-8")

    print(f"Splits: {path}")
    print(summary.to_string(float_format="%.3f"))


if __name__ == "__main__":
    main()
