"""Download Kepler light curves and build global/local views for the modelling sample.

One star at a time: download every long-cadence quarter (cached), mask the transits of all
KOIs on the star, detrend, then fold and bin each modelling-sample KOI. Stars with an
existing view file are skipped, so the build can be interrupted and resumed. Failures are
logged and retried on the next run.
"""

from __future__ import annotations

import argparse
import sys
import time
from concurrent.futures import ThreadPoolExecutor, as_completed
from pathlib import Path

import astroquery
import pandas as pd

from exoplanet.config import load_config
from exoplanet.data.catalogue import load_koi_catalogue
from exoplanet.data.labels import LABEL, label_catalogue
from exoplanet.data.lightcurves import build_star, load_views, star_path
from exoplanet.data.splits import KOI, load_splits
from exoplanet.reporting import markdown_table


def coverage_report(splits: pd.DataFrame, views: pd.DataFrame, failures: pd.DataFrame) -> str:
    built = splits[KOI].isin(views.index)
    by_label = (
        splits.assign(built=built)
        .groupby(LABEL)
        .agg(kois=(KOI, "size"), built=("built", "sum"), built_fraction=("built", "mean"))
    )
    qc = (
        views.join(splits.set_index(KOI)[LABEL])
        .groupby(LABEL)[["global_empty", "local_empty", "n_in_transit"]]
        .median()
        .add_prefix("median_")
    )
    lines = [
        "# Light-Curve Views",
        "",
        "Generated by `scripts/build_views.py`. Label 1 = CONFIRMED.",
        "",
        "## Coverage",
        "",
        markdown_table(by_label, floatfmt=".3f"),
        "",
        "## Quality (built KOIs)",
        "",
        "Empty fractions are the share of bins with no data before interpolation; "
        "`n_in_transit` counts points within half a duration of mid-transit.",
        "",
        markdown_table(qc, floatfmt=".3g"),
        "",
        f"## Failures this run: {len(failures)} stars",
        "",
    ]
    if len(failures):
        reasons = failures["error"].str.slice(0, 80).value_counts().rename("stars")
        lines += [markdown_table(reasons.rename_axis("error").to_frame()), ""]
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--config", default=None, help="path to a YAML config")
    parser.add_argument("--limit", type=int, default=None, help="process at most N new stars")
    parser.add_argument("--workers", type=int, default=4, help="stars processed in parallel")
    parser.add_argument("--kepid", type=int, nargs="*", help="only these host stars")
    parser.add_argument("--force", action="store_true", help="rebuild existing view files")
    parser.add_argument(
        "--output", default=None, help="report path (default: outputs/views_summary.md)"
    )
    args = parser.parse_args()

    # lightkurve silences downloads by swapping the global sys.stdout, which is not
    # thread-safe; print through the real console and restore it afterwards.
    console = sys.stdout
    astroquery.log.setLevel("WARNING")

    def log(message: str) -> None:
        print(message, file=console, flush=True)

    config = load_config(args.config)
    catalogue = load_koi_catalogue(config)
    sample = label_catalogue(catalogue, config)
    splits = load_splits(config)
    targets = sample[sample[KOI].isin(splits[KOI])]

    stars = sorted(targets["kepid"].unique())
    if args.kepid:
        stars = [s for s in stars if s in set(args.kepid)]
    todo = [s for s in stars if args.force or not star_path(s, config).exists()]
    if args.limit is not None:
        todo = todo[: args.limit]
    log(f"{len(stars)} stars in sample; building {len(todo)}")

    by_star_targets = dict(tuple(targets.groupby("kepid")))
    by_star_all = dict(tuple(catalogue.groupby("kepid")))
    failures, start = [], time.monotonic()
    with ThreadPoolExecutor(max_workers=args.workers) as pool:
        futures = {
            pool.submit(build_star, s, by_star_targets[s], by_star_all[s], config): s for s in todo
        }
        for i, future in enumerate(as_completed(futures), 1):
            star = futures[future]
            try:
                future.result()
            except Exception as exc:  # noqa: BLE001 - log and continue with other stars
                failures.append({"kepid": star, "error": f"{type(exc).__name__}: {exc}"})
            if i % 25 == 0 or i == len(todo):
                rate = i / (time.monotonic() - start)
                eta = (len(todo) - i) / rate / 60
                log(f"  {i}/{len(todo)} stars, {len(failures)} failed, ETA {eta:.0f} min")

    sys.stdout = console
    outputs = config["paths"]["outputs_dir"]
    outputs.mkdir(parents=True, exist_ok=True)
    failures = pd.DataFrame(failures, columns=["kepid", "error"])
    failures.to_csv(outputs / "views_failures.csv", index=False)

    views = load_views(config, splits[KOI])
    report = coverage_report(splits, views, failures)
    output = Path(args.output) if args.output else outputs / "views_summary.md"
    output.write_text(report, encoding="utf-8")
    log(f"{len(views)}/{len(splits)} KOIs have views; report: {output}")


if __name__ == "__main__":
    main()
